// -- hit case: the standard one-block "abc" vector, from node crypto ------
{
  const digest = specEngineSha256('abc');
  check(
    'sha256("abc") matches the node-crypto-generated digest',
    digest === 'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad'
  );
}

