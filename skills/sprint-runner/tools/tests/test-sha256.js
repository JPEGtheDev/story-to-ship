// Pure-JS SHA-256 suite for the sprint engine's dialect-neutral core.
//
// Runs as: node skills/sprint-runner/tools/tests/test-sha256.js
//
// Plain Node, no test framework, no dependencies beyond the module under
// test. Covers one function: specEngineSha256(str), a from-scratch
// SHA-256 implementation (FIPS 180-4) taking a JS string and returning the
// lowercase hex digest of that string's UTF-8 encoding. Not named in
// SPEC_SCHEMA.md -- this todo delivers only the hash function and its test
// suite, ahead of the spill-verification caller that will use it.
//
// All digests below were generated from node's own "crypto" module,
// OUTSIDE this suite and outside engine-core.js, and hard-coded here as
// the expected values: `node -e "console.log(require('crypto')
// .createHash('sha256').update(Buffer.from(STR, 'utf8')).digest('hex'))"`
// for each STR. The four vectors from the abc/empty/two-block/spill-
// threshold group and the boundary-length and non-ASCII groups were all
// independently confirmed this way before this suite was written.

'use strict';

const { specEngineSha256 } = require('../engine-core.js');

let passCount = 0;
let failCount = 0;

function check(description, condition) {
  if (condition) {
    passCount += 1;
  } else {
    failCount += 1;
    console.error('FAIL: ' + description);
  }
}

